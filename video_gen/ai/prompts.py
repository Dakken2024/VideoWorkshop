# ==================== 工具函数 ====================

PLATFORM_PROMPTS = {
    "wechat": {
        "name": "微信公众号",
        "system_prompt": WECHAT_PROMPT,
        "description": "深度长文，适合公众号传播",
    },
    "science": {
        "name": "知识科普",
        "system_prompt": SCIENCE_PROMPT,
        "description": "专业科普，数据支撑，深入浅出",
    },
    "short_video": {
        "name": "短视频脚本",
        "system_prompt": SHORT_VIDEO_PROMPT,
        "description": "短平快，适合抖音/视频号",
    },
    "scripts_json": {
        "name": "脚本生成",
        "system_prompt": SCRIPTS_JSON_PROMPT,
        "description": "将文章转为 scripts.json 格式",
    },
}


def get_platform_prompt(platform: str) -> str:
    """
    获取指定平台的系统提示词

    Args:
        platform: 平台标识（wechat, science, short_video, scripts_json）

    Returns:
        系统提示词文本
    """
    info = PLATFORM_PROMPTS.get(platform)
    if info:
        return info["system_prompt"]
    return WECHAT_PROMPT  # 默认返回微信公众号